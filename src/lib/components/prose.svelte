<h1 class="my-2 text-5xl text-mauve-200 underline">Why?</h1>
<p class="my-2 text-3xl text-mauve-400">What color is Mario? <br /></p>
<p class="my-2 text-3xl text-mauve-400">
	It sounds silly, but really! The <b>Nintendo Entertainment System</b> <i>itself</i> doesn't even
	know!<br />
</p>
<p class="my-2 text-3xl text-mauve-400">
	Unlike modern graphics, the NES doesn't store RGB color values. Games store
	<b>palette indexes</b> like
	<span class="border-2 border-mauve-800 bg-mauve-950 px-1 py-0.5 text-2xl">0x22</span> or
	<span class="border-2 border-mauve-800 bg-mauve-950 px-1 py-0.5 text-2xl">0x16</span> that then
	get directly converted into an analog NTSC video signal. The <i>display</i> was responsible for interpreting
	that signal as colors.
</p>
<p class="my-2 text-3xl text-mauve-400">
	Because of this, there is no one true answer for what colors the NES outputs. Dozens have tried,
	but nobody is truly right.
</p>
<p class="my-2 text-3xl text-mauve-400">Instead of the truth, I seek a different answer:</p>
<p class="my-2 text-center text-3xl text-mauve-300 italic">
	"What if I made people guess colors instead of a TV?"
</p>
<p class="my-2 text-3xl text-mauve-400">
	The color picker above will give you one of 13 hue values <a
		href="https://www.nesdev.org/wiki/PPU_palettes#Chroma"
		class="text-indigo-400 hover:underline">(based off this)</a
	>. Your job is to give it your best guess. These values will then be averaged to generate an NES
	emulator compatible color palette to be released and showcased in a video on my
	<a href="https://www.youtube.com/@ZombieNW" class="text-indigo-400 hover:underline"
		>YouTube Channel</a
	>.
</p>
<p class="my-2 text-3xl text-mauve-400 italic">Happy guessing!</p>
